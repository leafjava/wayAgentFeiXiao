import { config as loadEnv } from "dotenv";
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join } from "node:path";
import { createWalletClient, createPublicClient, http, defineChain } from "viem";
import { privateKeyToAccount } from "viem/accounts";
loadEnv();
loadEnv({ path: ".env.local", override: false });
const root = process.cwd();
const out = join(root, ".chain_runtime");
const rpc = process.env.MONAD_RPC ?? "https://testnet-rpc.monad.xyz";
const chainId = Number(process.env.MONAD_CHAIN_ID ?? 10143);
const chain = defineChain({ id: chainId, name: "Monad Testnet", nativeCurrency: { name: "MON", symbol: "MON", decimals: 18 }, rpcUrls: { default: { http: [rpc] } }, blockExplorers: { default: { name: "Monad Explorer", url: process.env.MONAD_EXPLORER ?? "https://testnet.monadexplorer.com" } }, testnet: true });
const pk = process.env.PRIVATE_KEY;
if (!pk) throw new Error("PRIVATE_KEY is not set");
if (!existsSync(join(out, "DisclosureRegistry.abi.json")) || !existsSync(join(out, "DisclosureRegistry.bin"))) throw new Error("Run npm run contract:compile first");
const account = privateKeyToAccount(("0x" + pk.replace(/^0x/, "")));
const abi = JSON.parse(readFileSync(join(out, "DisclosureRegistry.abi.json"), "utf8"));
const bytecode = ("0x" + readFileSync(join(out, "DisclosureRegistry.bin"), "utf8"));
const publicClient = createPublicClient({ chain, transport: http(rpc) });
const wallet = createWalletClient({ account, chain, transport: http(rpc) });
console.log(`Deploying from ${account.address} on Monad Testnet...`);
const hash = await wallet.deployContract({ abi, bytecode });
console.log(`Transaction: ${hash}`);
const receipt = await publicClient.waitForTransactionReceipt({ hash });
if (!receipt.contractAddress) throw new Error("Deployment receipt has no contract address");
const address = receipt.contractAddress;
mkdirSync(out, { recursive: true });
writeFileSync(join(out, "contract.json"), JSON.stringify({ address, deployer: account.address, txHash: hash, blockNumber: Number(receipt.blockNumber), chainId, rpc, abi, explorer: `${process.env.MONAD_EXPLORER ?? "https://testnet.monadexplorer.com"}/address/${address}` }, null, 2));
console.log(`DisclosureRegistry deployed: ${address}`);
console.log(`Set DISCLOSURE_REGISTRY_ADDRESS=${address}`);
